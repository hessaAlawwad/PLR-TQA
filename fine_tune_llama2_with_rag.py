def formatting_func(example):
    output_texts = []
    for i in range(len(example['question'])):
          context = str(example["Context"][i])
          options = str(example["answerChoices"][i])
          question = str(example["question"][i])
          answer = str(example["correctAnswer"][i])
          template = f"""<s>[INST]<<SYS>>\nYou are a helpful, respectful and honest assistant. Always answer as helpfully as possible using the context text provided. Your answers should only be the choice from the given multiple Options and not have any text after the answer is done.\n<</SYS>>\n\nContext: {context}\nQuestion: {question}\nOptions:{options}\nAnswer: [/INST]{answer}</s>"""
          prompt = template.replace("{question}", question).replace("{answer}", answer).replace("{context}", context).replace("{options}", options)
          output_texts.append(prompt)

    return output_texts

